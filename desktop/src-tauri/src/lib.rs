mod commands;

use tauri::Manager;

pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .setup(|app| {
            #[cfg(windows)]
            {
                use window_vibrancy::apply_mica;
                if let Some(window) = app.get_webview_window("main") {
                    let _ = apply_mica(&window, Some(true));
                }
            }
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            commands::init_app,
            commands::ensure_device_vault,
            commands::load_settings,
            commands::save_settings,
            commands::volumes,
            commands::list_servers,
            commands::save_server,
            commands::delete_server,
            commands::save_group,
            commands::delete_group,
            commands::connect_server,
            commands::cancel_connect,
            commands::connect_stage,
            commands::disconnect_session,
            commands::home_local,
            commands::list_local,
            commands::list_remote,
            commands::mkdir,
            commands::rename,
            commands::remove,
            commands::copy_local,
            commands::transfer_file,
            commands::cancel_transfer,
            commands::download_to_cache,
            commands::preview,
            commands::save_text,
            commands::checksum,
            commands::find_files,
            commands::chmod,
            commands::probe_server,
            commands::check_server_access,
            commands::set_secret,
            commands::get_secret,
            commands::delete_secret,
            commands::load_color_rules,
            commands::save_color_rules,
            commands::load_snippets,
            commands::save_snippet,
            commands::delete_snippet,
            commands::save_snippet_order,
            commands::load_ai_settings,
            commands::save_ai_settings,
            commands::load_session_state,
            commands::save_open_sessions,
            commands::remember_session,
            commands::open_shell,
            commands::shell_write,
            commands::shell_poll,
            commands::shell_close,
            commands::export_profile,
            commands::import_profile,
            commands::credentials_preview,
            commands::export_credentials,
            commands::sync_export_json,
            commands::import_sync,
            commands::start_sync_share,
            commands::stop_sync_share,
            commands::sync_share_token,
            commands::import_sync_url,
            commands::lock_vault,
            commands::unlock_vault,
            commands::vault_info,
            commands::reveal_in_explorer,
            commands::open_terminal_at,
            commands::launch_process,
            commands::launch_editor,
            commands::path_exists,
            commands::upload_from_cache,
            commands::file_mtime_ms,
            commands::append_edit_log,
            commands::ui_log,
            commands::set_solid_mode,
            commands::clear_server_tmp,
            commands::clear_all_tmp,
            commands::exec_remote,
            commands::upgrade_vault_to_device_key,
            commands::ai_models,
            commands::ai_ask,
            commands::compare_files,
            commands::compare_text,
            commands::resolve_remote_dir,
            commands::sync_scan,
            commands::log_dir,
            commands::load_log_settings,
            commands::save_log_settings,
            commands::import_winscp_ini,
            commands::list_logs,
            commands::read_log,
            commands::archive_needs_password,
            commands::unlock_archive,
            commands::list_archive,
            commands::preview_archive,
            commands::create_archive,
            commands::copy_to_archive,
            commands::assemble_volumes,
            commands::cancel_archive_task,
            commands::cancel_archive_job,
            commands::copy_from_archive,
            commands::pack_server_archive,
            commands::unpack_server_archive,
        ])
        .run(tauri::generate_context!())
        .expect("error while running the NovaSSH desktop app");
}
